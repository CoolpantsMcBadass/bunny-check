// ─── CSV helpers ─────────────────────────────────────────────────────────────

function splitRow(line) {
  const cells = []; let cur = "", inQ = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (inQ) {
      if (ch === '"' && line[i+1] === '"') { cur += '"'; i++; }
      else if (ch === '"') inQ = false;
      else cur += ch;
    } else {
      if (ch === '"') inQ = true;
      else if (ch === ',') { cells.push(cur); cur = ""; }
      else cur += ch;
    }
  }
  cells.push(cur);
  return cells;
}

function q(v) {
  v = String(v ?? "");
  return (v.includes(",") || v.includes('"') || v.includes("\n"))
    ? '"' + v.replace(/"/g, '""') + '"' : v;
}

